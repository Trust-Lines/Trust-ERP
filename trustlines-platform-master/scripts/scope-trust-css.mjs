// Scopes the Trust System stylesheet under `.trust-projects` so it can't touch T-ERP and
// T-ERP's base styles can't reach the board (modules/trust-projects/styles.css → scoped.css).
// Re-run after replacing styles.css with a newer copy:  node scripts/scope-trust-css.mjs
//
// Rules: selectors get the `.trust-projects ` prefix; `html`, `body` and `:root` become
// the wrapper itself (`#root` stays a normal, prefixed selector); `*` becomes `.trust-projects, .trust-projects *`. Keyframes are left alone.
// On the html/body rule, `overflow*` and `height` are dropped: on the wrapper they would make it
// a scroll container and break the board's sticky headers (on <html>/<body> they don't).
/* global console */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const dir = path.resolve('modules/trust-projects');
const SCOPE = '.trust-projects';
const ROOTISH = /^(html|body|:root)$/;

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  if (s === '*') return `${SCOPE}, ${SCOPE} *`;
  if (ROOTISH.test(s)) return SCOPE;
  const m = s.match(/^(html|body|:root)((?:[.#:[][^\s>+~]*)?)(\s*[>+~]?\s*)(.*)$/);
  if (m && (m[2] || m[4])) return `${SCOPE}${m[2]}${m[4] ? ` ${m[4]}` : ''}`;
  if (s.startsWith(SCOPE)) return s;
  return `${SCOPE} ${s}`;
}

const css = fs.readFileSync(path.join(dir, 'styles.css'), 'utf8');
const root = postcss.parse(css);
root.walkRules(rule => {
  for (let p = rule.parent; p; p = p.parent) if (p.type === 'atrule' && /keyframes$/i.test(p.name)) return;
  const wasPage = rule.selectors.some(s => /^(html|body)$/.test(s.trim()));
  rule.selectors = [...new Set(rule.selectors.flatMap(s => scopeSelector(s).split(/,\s*/)))];
  if (wasPage) rule.walkDecls(d => { if (/^(overflow(-[xy])?|height)$/.test(d.prop)) d.remove(); });
});

const header = '/* GENERATED by scripts/scope-trust-css.mjs from styles.css — do not edit by hand. */\n';
fs.writeFileSync(path.join(dir, 'styles.scoped.css'), header + root.toString());
console.log('scoped', root.nodes.length, 'top-level nodes');
